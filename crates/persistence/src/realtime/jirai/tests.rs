fn online_entry(created_at: &str, location: &str, world_name: &str) -> FeedLiveEntry {
    FeedLiveEntry::Online {
        created_at: created_at.into(),
        user_id: "usr_friend".into(),
        display_name: "Friend".into(),
        location: location.into(),
        world_name: world_name.into(),
        group_name: String::new(),
        time: None,
        world_id: None,
        display_location: None,
        owner_user_id: String::new(),
    }
}

struct TestDir {
    path: PathBuf,
}

impl TestDir {
    fn new(name: &str) -> Self {
        let nonce = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let path =
            std::env::temp_dir().join(format!("vrcx-0-{name}-{}-{nonce}", std::process::id()));
        std::fs::create_dir_all(&path).unwrap();
        Self { path }
    }
}

impl Drop for TestDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.path);
    }
}

fn add_startup_current_friend(
    db: &DatabaseService,
    owner: &OwnerId,
    user_id: &str,
) -> Result<(), crate::Error> {
    write_realtime_batch(
        db,
        owner,
        &RealtimePersistenceBatch {
            friend_log_upserts: vec![FriendLogUpsert {
                target_user_id: user_id.into(),
                display_name: user_id.into(),
                trust_level: "Known User".into(),
                friend_number: 1,
                created_at: "2026-05-15T10:00:00Z".into(),
                force_history: false,
            }],
            ..RealtimePersistenceBatch::default()
        },
    )?;
    Ok(())
}

#[test]
fn startup_online_backfill_writes_only_current_friends_with_native_now() -> Result<(), crate::Error>
{
    let dir = TestDir::new("startup-online-backfill");
    let db = DatabaseService::new(&dir.path.join("VRCX-0.sqlite3"))?;
    let owner = OwnerId::new("usr_self");
    for user_id in ["usr_missing", "usr_offline", "usr_friend"] {
        add_startup_current_friend(&db, &owner, user_id)?;
    }

    // No prior Online/Offline state inserts exactly one event, even when the
    // same friend is repeated in the startup batch. The persisted timestamp is
    // generated by Rust, not supplied by a renderer argument.
    let before = vrcx_0_core::time::now_iso();
    assert!(insert_startup_online_backfill(
        &db,
        &owner,
        "usr_missing",
        "Missing History",
    )?);
    assert!(!insert_startup_online_backfill(
        &db,
        &owner,
        "usr_missing",
        "Missing History",
    )?);
    let after = vrcx_0_core::time::now_iso();

    // An Offline edge is replaced by the observed-now Online edge.
    write_realtime_batch(
        &db,
        &owner,
        &RealtimePersistenceBatch {
            feed_entries: vec![FeedLiveEntry::Offline {
                created_at: "2026-05-15T11:00:00Z".into(),
                user_id: "usr_offline".into(),
                display_name: "Offline Friend".into(),
                location: String::new(),
                world_name: String::new(),
                group_name: String::new(),
                time: None,
                world_id: None,
                display_location: None,
                owner_user_id: String::new(),
            }],
            ..RealtimePersistenceBatch::default()
        },
    )?;
    assert!(insert_startup_online_backfill(
        &db,
        &owner,
        "usr_offline",
        "Offline Friend",
    )?);

    // A final Online edge remains untouched.
    write_realtime_batch(
        &db,
        &owner,
        &RealtimePersistenceBatch {
            feed_entries: vec![online_entry("2026-05-15T11:30:00Z", "", "")],
            ..RealtimePersistenceBatch::default()
        },
    )?;
    assert!(!insert_startup_online_backfill(
        &db,
        &owner,
        "usr_friend",
        "Friend",
    )?);

    let rows = crate::feed::feed_rows_query(
        &db,
        crate::feed::FeedRowsQueryInput {
            user_id: "usr_self".into(),
            mode: crate::feed::FeedQueryMode::Lookup,
            search: String::new(),
            filters: vec![crate::feed::FeedFilter::Online],
            vip_list: Vec::new(),
            scoped_user_ids: vec!["usr_missing".into()],
            excluded_user_ids: Vec::new(),
            location_hidden_user_ids: Vec::new(),
            max_entries: 10,
            date_from: String::new(),
            date_to: String::new(),
            cursor: None,
        },
    )?;
    assert_eq!(rows.len(), 1);
    assert_eq!(rows[0].user_id.as_deref(), Some("usr_missing"));
    let created_at = rows[0].created_at.as_deref().unwrap();
    assert!(created_at >= before.as_str() && created_at <= after.as_str());
    assert_eq!(rows[0].r#type.as_deref(), Some("Online"));

    // A non-friend cannot create a feed edge through this native boundary.
    let non_friend =
        insert_startup_online_backfill(&db, &owner, "usr_nonfriend", "Not A Friend").unwrap_err();
    assert!(matches!(non_friend, crate::Error::InvalidData(_)));

    // User-prefixed Feed tables keep different owners independent.
    let other_owner = OwnerId::new("usr_other");
    add_startup_current_friend(&db, &other_owner, "usr_missing")?;
    assert!(insert_startup_online_backfill(
        &db,
        &other_owner,
        "usr_missing",
        "Missing History",
    )?);
    Ok(())
}

#[test]
fn profile_feed_reconcile_records_only_owner_scoped_changes() -> Result<(), crate::Error> {
    let dir = TestDir::new("profile-feed-reconcile");
    let db = DatabaseService::new(&dir.path.join("VRCX-0.sqlite3"))?;
    let owner = OwnerId::new("usr_self");
    let input = || ProfileFeedReconcileInput {
        user_id: "usr_friend".into(),
        display_name: "Friend".into(),
        bio: String::new(),
        status: "active".into(),
        status_description: "first".into(),
    };
    let first = profile_feed_reconcile(&db, &owner, input())?;
    assert!(first.bio_updated && first.status_updated);
    let repeated = profile_feed_reconcile(&db, &owner, input())?;
    assert!(!repeated.bio_updated && !repeated.status_updated);
    let description_changed = profile_feed_reconcile(
        &db,
        &owner,
        ProfileFeedReconcileInput {
            status_description: "changed".into(),
            ..input()
        },
    )?;
    assert!(!description_changed.bio_updated && description_changed.status_updated);
    let disallowed = profile_feed_reconcile(
        &db,
        &owner,
        ProfileFeedReconcileInput {
            status: "offline".into(),
            status_description: "ignored".into(),
            ..input()
        },
    )?;
    assert!(!disallowed.status_updated);

    let other = OwnerId::new("usr_other");
    assert!(profile_feed_reconcile(&db, &other, input())?.bio_updated);
    let self_bio = db.execute(
        "SELECT COUNT(*) FROM usrself_feed_bio",
        &ParamsBuilder::new().build(),
    )?;
    let other_bio = db.execute(
        "SELECT COUNT(*) FROM usrother_feed_bio",
        &ParamsBuilder::new().build(),
    )?;
    let self_status = db.execute(
        "SELECT COUNT(*) FROM usrself_feed_status",
        &ParamsBuilder::new().build(),
    )?;
    assert_eq!(self_bio[0][0].as_i64(), Some(1));
    assert_eq!(other_bio[0][0].as_i64(), Some(1));
    assert_eq!(self_status[0][0].as_i64(), Some(2));
    Ok(())
}
